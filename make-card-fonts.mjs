// Writes worker/card-fonts.mjs: the Lao and number fonts as data URLs for the picture cards (Facebook
// posts, storm link previews). Cloudflare Browser Run did not load Google Fonts (28 Oct 2026) and its
// fallback font stacked Lao vowels and tone marks wrongly (ມື້ນີ້), so the cards carry their own fonts.
// Sources: dist/fonts/noto-sans-lao.woff2 (Noto Sans Lao, Lao subset, variable weight) and
// dist/fonts/inter-latin.woff2 (Inter, Latin subset), both from Google Fonts, SIL Open Font License 1.1.
import fs from 'node:fs';
const b64=f=>fs.readFileSync(new URL('./dist/fonts/'+f,import.meta.url)).toString('base64');
const face=(family,file)=>`@font-face{font-family:'${family}';src:url(data:font/woff2;base64,${b64(file)}) format('woff2');font-weight:100 900;font-display:block}`;
const css=face('Noto Sans Lao','noto-sans-lao.woff2')+face('Inter','inter-latin.woff2');
fs.writeFileSync(new URL('./worker/card-fonts.mjs',import.meta.url),`// Generated by make-card-fonts.mjs. Do not edit. Fonts: SIL Open Font License 1.1 (Noto Sans Lao, Inter).\nexport const CARD_FONTS=${JSON.stringify(css)};\n`);
console.log('card-fonts.mjs',css.length,'characters');
