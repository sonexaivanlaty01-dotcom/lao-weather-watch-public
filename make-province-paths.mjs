// Writes worker/lao-province-paths.mjs: one small SVG path per province (Web Mercator, viewBox
// 0 0 600 H) for the Facebook post cards (worker/fb-bot.mjs). Source: dist/data/admin/provinces.geojson.
import fs from 'node:fs';
import {PROVINCES} from './worker/seo-provinces.mjs';
const geo=JSON.parse(fs.readFileSync(new URL('./dist/data/admin/provinces.geojson',import.meta.url),'utf8'));
const W=600,LON0=100,LON1=107.75,LAT0=13.85,LAT1=22.55,my=lat=>Math.log(Math.tan(Math.PI/4+lat*Math.PI/360));
const k=W/((LON1-LON0)*Math.PI/180),H=Math.round((my(LAT1)-my(LAT0))*k);
const X=lon=>(lon-LON0)*Math.PI/180*k,Y=lat=>(my(LAT1)-my(lat))*k;
const out={};
for(const f of geo.features){
 const slug=PROVINCES.find(p=>p.name_en===f.properties.name_en)?.slug;if(!slug)throw new Error('no slug for '+f.properties.name_en);
 const polys=f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.coordinates;let d='';
 for(const poly of polys){const ring=poly[0];let last=null,pts=[];
  for(const [lon,lat] of ring){const p=[X(lon),Y(lat)];if(last&&Math.hypot(p[0]-last[0],p[1]-last[1])<1.6)continue;pts.push(p);last=p}
  if(pts.length>=3)d+='M'+pts.map(p=>p[0].toFixed(1)+' '+p[1].toFixed(1)).join('L')+'Z'}
 out[slug]=d}
const labels=Object.fromEntries(PROVINCES.map(p=>[p.slug,[Math.round(X(p.center[0])),Math.round(Y(p.center[1]))]]));
fs.writeFileSync(new URL('./worker/lao-province-paths.mjs',import.meta.url),`// Generated by make-province-paths.mjs from dist/data/admin/provinces.geojson. Do not edit.\nexport const PROVINCE_VIEW=[${W},${H}];\nexport const PROVINCE_PATHS=${JSON.stringify(out)};\nexport const PROVINCE_LABELS=${JSON.stringify(labels)};\n`);
console.log('ok',W,H,Object.keys(out).length,Object.values(out).reduce((a,d)=>a+d.length,0)+' chars');
